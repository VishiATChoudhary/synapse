// Bridge between the renderer and the main process. Nothing from Node leaks into the page.
const { contextBridge, ipcRenderer } = require('electron');

const call = (ch, args) => ipcRenderer.invoke(ch, args).then((r) => { if (!r.ok) throw new Error(r.error); return r.value; });
const on = (ch, fn) => { const h = (_e, a) => fn(a); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };

contextBridge.exposeInMainWorld('synapse', {
  state: () => call('state'),
  flags: () => call('flags'),
  onState: (fn) => on('state', fn),
  notify: { done: (a) => call('notify:done', a), onOpen: (fn) => on('notify:open', fn) },
  pty: {
    spawn: (a) => call('pty:spawn', a),
    restore: (a) => call('pty:restore', a),
    write: (id, data) => call('pty:write', { id, data }),
    submit: (id, text) => call('pty:submit', { id, text }),
    resize: (id, cols, rows) => call('pty:resize', { id, cols, rows }),
    kill: (id) => call('pty:kill', { id }),
    onData: (fn) => on('pty:data', fn),
    onExit: (fn) => on('pty:exit', fn),
  },
  sessions: { load: () => call('sessions:load'), save: (data) => call('sessions:save', data) },
  workspace: { load: () => call('workspace:load'), save: (key, value) => call('workspace:save', { key, value }) },
  phone: {
    devices: () => call('phone:devices'),
    allow: (id) => call('phone:allow', { id }),
    remove: (id) => call('phone:remove', { id }),
    onSpawn: (fn) => on('phone:spawn', fn),
    onChanged: (fn) => on('phone:changed', fn),
    shares: () => call('phone:shares'),
    unshare: (id) => call('phone:unshare', { id }),
    onShow: (fn) => on('phone:show', fn),
  },
  fork: { spawn: (a) => call('fork:spawn', a), link: (child, parent) => call('fork:link', { child, parent }), onRequest: (fn) => on('fork:request', fn) },
  project: {
    add: (p) => call('project:add', { path: p }),
    create: (name) => call('project:create', { name }),
    clone: (url, name) => call('project:clone', { url, name }),
    pick: () => call('project:pick'),
    library: () => call('project:library'),
    remove: (p) => call('project:remove', { path: p }),
    order: (keys) => call('project:order', { keys }),
    rename: (key, name) => call('project:rename', { key, name }),
    onCloneProgress: (fn) => on('clone:progress', fn),
  },
  worktree: { list: (repo) => call('worktree:list', { repo }), open: (a) => call('worktree:open', a), fetch: (repo) => call('worktree:fetch', { repo }), prs: (repo, choices) => call('worktree:prs', { repo, choices }), add: (a) => call('worktree:add', a), remove: (a) => call('worktree:remove', a), rename: (path, name) => call('worktree:rename', { path, name }), order: (paths) => call('worktree:order', { paths }) },
  settings: { usage: () => call('talk:usage'), get: () => call('settings:get'), set: (patch) => call('settings:set', patch) },
  git: { dirty: (cwd) => call('git:dirty', { cwd }) },
  agent: { kill: (pid) => call('agent:kill', { pid }), rename: (pty, name) => call('agent:rename', { pty, name }) },
  account: {
    get: () => call('account:get'),
    skipped: () => call('account:skipped'),
    skip: () => call('account:skip'),
    signup: (a) => call('account:signup', a),
    login: (a) => call('account:login', a),
    logout: () => call('account:logout'),
    providers: () => call('account:providers'),
    device: (provider) => call('account:device', { provider }),
    cancelDevice: () => call('account:device-cancel'),
    onDevice: (fn) => on('device', fn),
    me: () => call('account:me'),
    update: (patch) => call('account:update', patch),
    password: (a) => call('account:password', a),
    forgot: (email) => call('account:forgot', { email }),
    resend: () => call('account:resend'),
    openWeb: (path) => call('account:web', { path }),
    onChange: (fn) => on('account', fn),
  },
  onboarding: { get: () => call('onboarding:get'), done: () => call('onboarding:done') },
  integrations: { preview: () => call('integrations:preview'), install: () => call('integrations:install') },
  shares: { mode: (id, mode) => call('share:mode', { id, mode }), remove: (id) => call('share:remove', { id }) },
  people: { list: () => call('people:list'), add: (who) => call('people:add', { who }), remove: (id) => call('people:remove', { id }),
    trustBack: (id, handle) => call('trust:back', { id, handle }), ignore: (id) => call('trust:ignore', { id }) },
  requests: {
    list: () => call('requests:list'),
    agents: () => call('requests:agents'),
    accept: (id, agents, talk = true) => call('requests:accept', { id, agents, talk }),
    acceptOffer: (id, receiver) => call('requests:acceptOffer', { id, receiver }),
    offer: (to, agent, mode) => call('share:offer', { to, agent, mode }),
    deny: (id) => call('requests:deny', { id }),
    cancel: (id) => call('requests:cancel', { id }),
    onChange: (fn) => on('requests', fn),
    onOpen: (fn) => on('requests:open', fn),
  },
  update: { get: () => call('update:get'), check: () => call('update:check'), install: () => call('update:install'), download: () => call('update:download'), onChange: (fn) => on('update', fn) },
  links: () => call('links'),
  onLoginSuggest: (fn) => on('login:suggest', fn),
  talks: { list: () => call('talks:list'), onOpen: (fn) => on('talk:open', fn) },
  activity: { get: () => call('activity:get'), onProgress: (fn) => on('activity:progress', fn) },
  board: { get: () => call('board:get'), join: () => call('board:join'), leave: () => call('board:leave') },
  talkRequests: { allow: (id) => call('talkreq:allow', { id }), dismiss: (id) => call('talkreq:dismiss', { id }) },
  cli: (args, as) => call('synapse', { args, as }),
  canvas: () => call('canvas'),
  onCanvasToggle: (fn) => on('canvas:toggle', fn),
  onCanvasBack: (fn) => on('canvas:back', fn),
});
